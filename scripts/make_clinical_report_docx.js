function h1(text) {
    return new Paragraph({
        heading: HeadingLevel.HEADING_1,
        spacing: { before: 400, after: 180 },
        children: [new TextRun({ text: text, bold: true, size: 32, color: "1F3864" })],
    });
}

function h2(text) {
    return new Paragraph({
        heading: HeadingLevel.HEADING_2,
        spacing: { before: 280, after: 140 },
        children: [new TextRun({ text: text, bold: true, size: 26, color: "2E75B6" })],
    });
}

function h3(text) {
    return new Paragraph({
        heading: HeadingLevel.HEADING_3,
        spacing: { before: 200, after: 100 },
        children: [new TextRun({ text: text, bold: true, size: 22, color: "404040" })],
    });
}

function p(text, opts = {}) {
    return new Paragraph({
        spacing: { after: 120 },
        alignment: opts.align || AlignmentType.LEFT,
        children: [new TextRun({ text: text, size: 22, ...opts })],
    });
}

function pBold(text) {
    return p(text, { bold: true });
}

function pMixed(runs, opts = {}) {
    return new Paragraph({
        spacing: { after: 120 },
        children: runs.map(r => new TextRun({ size: 22, ...r })),
    });
}

function bullet(text, level = 0) {
    return new Paragraph({
        numbering: { reference: "bullets", level: level },
        spacing: { after: 80 },
        children: [new TextRun({ text: text, size: 22 })],
    });
}

function bulletMixed(runs, level = 0) {
    return new Paragraph({
        numbering: { reference: "bullets", level: level },
        spacing: { after: 80 },
        children: runs.map(r => new TextRun({ size: 22, ...r })),
    });
}

function numbered(text, level = 0) {
    return new Paragraph({
        numbering: { reference: "numbers", level: level },
        spacing: { after: 80 },
        children: [new TextRun({ text: text, size: 22 })],
    });
}

function tableCell(text, opts = {}) {
    return new TableCell({
        borders,
        width: { size: opts.width || 3120, type: WidthType.DXA },
        shading: opts.shade ? { fill: opts.shade, type: ShadingType.CLEAR } : undefined,
        margins: { top: 80, bottom: 80, left: 120, right: 120 },
        children: [new Paragraph({
            alignment: opts.align || AlignmentType.LEFT,
            children: [new TextRun({ text: text, size: 20, bold: opts.bold })],
        })],
    });
}

function headerRow(cols, widths) {
    return new TableRow({
        tableHeader: true,
        children: cols.map((c, i) => tableCell(c, {
            width: widths[i], bold: true, align: AlignmentType.CENTER, shade: "D9E2F3",
        })),
    });
}

function dataRow(cols, widths, opts = {}) {
    return new TableRow({
        children: cols.map((c, i) => tableCell(c, {
            width: widths[i], align: opts.align || AlignmentType.LEFT,
            bold: opts.bold, shade: opts.shade,
        })),
    });
}

